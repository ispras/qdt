__all__ = [
    "ready"
]


class ready:
    """ A method @decorator.
It defines a read-only, target, attribute.
This decorator tracks readiness state of required attributes.
A data descriptor for a required attribute is generated by `ready.bit`.
The method is called with `True` when
    all required attributes has been `__set__`.
It may `return` a value for the target attribute.
Note, `None` is default function `return` value.
The method is called with `False` when
    all required attributes has been `__set__`
    but one of them is going to be `__set__` or `__delete__`-d.
Returned value is ignored.
The target attribute is `__delete__`-d.
    """

    def __init__(self, handler):
        self.handler = handler
        self.mask = 0
        self.next_bit = 0

    def __set_name__(self, o, name):
        self.public = name
        self.private = "_" + name
        self.ready = ready = name + "_ready"
        setattr(o, ready, 0)

    def __get__(self, o, t = None):
        return getattr(o, self.private)

    def bit(self, bit = None):
        if bit is None:
            bit = self.next_bit
            self.next_bit = bit + 1
        flag = 1 << bit
        mask = self.mask
        if flag & mask:
            raise ValueError("%s: bit %d is already used" % (
                self.public,
                bit,
            ))
        self.mask = mask | flag
        return _Ready(flag, bitfield = self)


class _Ready:

    def __init__(self, mask, bitfield):
        self.mask = mask
        self.clear = ~mask
        self.bitfield = bitfield

    def __set_name__(self, o, name):
        self.public = name
        self.private = "_" + name

    def __get__(self, o, t = None):
        try:
            return getattr(o, self.private)
        except AttributeError:
            raise AttributeError(self.public)

    def __set__(self, o, v):
        bf = self.bitfield
        f = bf.ready
        ready_mask = bf.mask
        private = self.private
        try:
            getattr(o, private)
        except AttributeError:
            pass  # Has never been set yet.
        else:
            mask = getattr(o, f)
            setattr(o, f, mask & self.clear)
            if mask == ready_mask:
                bf.handler(o, False)
                delattr(o, bf.private)
        setattr(o, private, v)
        mask = getattr(o, f) | self.mask
        setattr(o, f, mask)
        if mask == bf.mask:
            setattr(o, bf.private, bf.handler(o, True))

    def __delete__(self, o):
        f = self.bitfield.public
        private = self.private
        if hasattr(o, private):
            setattr(o, f, getattr(o, f) & self.clear)
            delattr(o, private)
        else:
            raise AttributeError(self.public)

